import {readFile,writeFile} from 'node:fs/promises'
import './build-plan-config.mjs'
const files=['056_master_workspace.sql','057_support_workspace.sql','058_shift_defaults.sql','059_plans_solo.sql']
async function bundle(kind,order){
 const bodies=await Promise.all(order.map(async file=>{
  const sql=(await readFile(new URL('../supabase/'+kind+'/'+file,import.meta.url),'utf8')).trim()
  if(!/^(?:--[^\n]*\n\s*)*begin;/i.test(sql)||!/commit;$/i.test(sql))throw Error('Transaction wrapper missing: '+file)
  return '-- '+file+'\n'+sql.replace(/^begin;\s*/im,'').replace(/commit;$/i,'').trim()
 }))
 return '-- Generated by scripts/build-unified-refactor.mjs. Apply as one transaction.\nbegin;\n'+bodies.join('\n\n')+'\ncommit;\n'
}
await writeFile(new URL('../supabase/deploy/unified_056_059.sql',import.meta.url),await bundle('migrations',files))
await writeFile(new URL('../supabase/rollback/unified_056_059.sql',import.meta.url),await bundle('rollback',[...files].reverse()))
